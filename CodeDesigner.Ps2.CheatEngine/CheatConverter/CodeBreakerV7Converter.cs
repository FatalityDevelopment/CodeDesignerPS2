                    else
                    {
                        for (int i = 0; i < 5; i++) Array.Clear(Seeds[i], 0, 256);
                        Key[0] = Key[1] = Key[2] = Key[3] = 0;
                    }
                }

                // Use ARCFOUR to scramble the seed tables using the current key
                for (int i = 0; i < 5; i++)
                {
                    byte[] keyBytes = new byte[20];
                    Buffer.BlockCopy(Key, 0, keyBytes, 0, 20);
                    var arc4 = new Arc4(keyBytes);
                    arc4.Process(Seeds[i]);
                    arc4.Process(keyBytes);
                    Buffer.BlockCopy(keyBytes, 0, Key, 0, 20);
                }
            }

            private void SetKeyFromSeeds(byte p0, byte p1, byte p2, byte p3)
            {
                Key[0] = (uint)((Seeds[3][p3] << 24) | (Seeds[2][p2] << 16) | (Seeds[1][p1] << 8) | Seeds[0][p0]);
                Key[1] = (uint)((Seeds[0][p3] << 24) | (Seeds[3][p2] << 16) | (Seeds[2][p1] << 8) | Seeds[1][p0]);
                Key[2] = (uint)((Seeds[1][p3] << 24) | (Seeds[0][p2] << 16) | (Seeds[3][p1] << 8) | Seeds[2][p0]);
                Key[3] = (uint)((Seeds[2][p3] << 24) | (Seeds[1][p2] << 16) | (Seeds[0][p1] << 8) | Seeds[3][p0]);
            }
        }

        // -----------------------------------------------------------------------
        // Per-code encrypt / decrypt  (multi-step CB7 cipher)
        // -----------------------------------------------------------------------

        private static (uint addr, uint val) Cb7Decrypt(uint encAddr, uint encVal, Cb7State state)
        {
            byte[] keyBytes = new byte[20];
            Buffer.BlockCopy(state.Key, 0, keyBytes, 0, 20);

            // Step 1: modular-multiplicative-inverse decrypt
            uint a = MulDecrypt(encAddr, keyBytes[0]);
            uint v = MulDecrypt(encVal,  keyBytes[4]);

            // Step 2: ARCFOUR stream byte
            var arc4 = new Arc4(keyBytes);
            var twoWords = new byte[8];
            Buffer.BlockCopy(new[] { a, v }, 0, twoWords, 0, 8);
            arc4.Process(twoWords);
            a = BitConverter.ToUInt32(twoWords, 0);
            v = BitConverter.ToUInt32(twoWords, 4);

            // Step 3: RSA-like modular exponentiation
            ulong code64 = ((ulong)a << 32) | v;
            if (code64 < RsaModulus)
                code64 = ModPow64(code64, RsaDecKey, RsaModulus);

            a = (uint)(code64 >> 32);
            v = (uint)(code64);
            return (a, v);
        }

        private static (uint addr, uint val) Cb7Encrypt(uint addr, uint val, Cb7State state)
        {
            // Step 1: RSA-like modular exponentiation (inverse direction)
            ulong code64 = ((ulong)addr << 32) | val;
            if (code64 < RsaModulus)
                code64 = ModPow64(code64, RsaEncKey, RsaModulus);

            uint a = (uint)(code64 >> 32);
            uint v = (uint)(code64);

            byte[] keyBytes = new byte[20];
            Buffer.BlockCopy(state.Key, 0, keyBytes, 0, 20);

            // Step 2: ARCFOUR stream byte
            var arc4 = new Arc4(keyBytes);
            var twoWords = new byte[8];
            Buffer.BlockCopy(new[] { a, v }, 0, twoWords, 0, 8);
            arc4.Process(twoWords);
            a = BitConverter.ToUInt32(twoWords, 0);
            v = BitConverter.ToUInt32(twoWords, 4);

            // Step 3: modular multiplication
            a = MulEncrypt(a, keyBytes[0]);
            v = MulEncrypt(v, keyBytes[4]);

            return (a, v);
        }

        // -----------------------------------------------------------------------
        // Regex
        // -----------------------------------------------------------------------

        private static readonly Regex HexPair =
            new Regex(@"^([0-9A-Fa-f]{8})\s+([0-9A-Fa-f]{8})$", RegexOptions.Compiled);

        // -----------------------------------------------------------------------
        // ICheatCodeConverter
        // -----------------------------------------------------------------------

        /// <inheritdoc/>
        public IReadOnlyList<RawCode> Decode(string input)
        {
            var result = new List<RawCode>();
            var state  = new Cb7State();
            bool active = false;

            var lines = input.Split('\n');

            // If no BEEFC0DE/BEEFC0DF key line is present, assume the entire input is
            // CB7-encrypted with the default seed (0).  This matches the output of
            // Encode() when called without an explicit beefcode, and allows users to
            // paste raw CB7 code lines without the BEEFC0DE header and still obtain
            // the correct plaintext.
            bool hasBeefcode = false;
            foreach (var rawLine in lines)
            {
                var line = rawLine.Trim();
                var m = HexPair.Match(line);
                if (!m.Success) continue;
                uint addr = Convert.ToUInt32(m.Groups[1].Value, 16);
                if (addr == BeefCode || addr == BeefCodeF) { hasBeefcode = true; break; }
            }

            if (!hasBeefcode)
            {
                state.Beefcode(true, 0x00000000);
                active = true;
            }

            foreach (var rawLine in lines)
            {
                var line = rawLine.Trim();
                var m = HexPair.Match(line);
                if (!m.Success) continue;

                uint encAddr = Convert.ToUInt32(m.Groups[1].Value, 16);
                uint encVal  = Convert.ToUInt32(m.Groups[2].Value, 16);

                if (encAddr == BeefCode || encAddr == BeefCodeF)
                {
                    // BEEFC0DE activates V7 encryption and sets the key
                    state.Beefcode(!active, encVal);
                    active = true;
                    continue;
                }

                if (active)
                {
                    var (addr, val) = Cb7Decrypt(encAddr, encVal, state);
                    result.Add(new RawCode(addr, val));
                }
                else
                {
                    // Pre-beefcode lines: use CB1 passthrough (unencrypted or V1-encrypted)
                    result.Add(new RawCode(encAddr, encVal));
                }
            }
            return result;
        }

        /// <inheritdoc/>
        public string Encode(IEnumerable<RawCode> codes)
        {
            var state  = new Cb7State();
            state.Beefcode(true, 0x00000000); // default beefcode seed = 0

            var sb = new StringBuilder();
            // Emit the BEEFC0DE key line
            sb.AppendLine($"{BeefCode:X8} 00000000");

            foreach (var code in codes)
            {
                var (encAddr, encVal) = Cb7Encrypt(code.Address, code.Value, state);
                sb.AppendLine($"{encAddr:X8} {encVal:X8}");
            }
            return sb.ToString().TrimEnd();
        }
