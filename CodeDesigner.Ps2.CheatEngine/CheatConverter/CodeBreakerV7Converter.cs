        /// <summary>
        /// Computes the modular multiplicative inverse of <paramref name="word"/> modulo 2³².
        /// Returns <c>x</c> such that <c>(word * x) mod 2³² = 1</c> using an extended
        /// Euclidean algorithm.  Ported from <c>MulInverse()</c> in cb2util/cb2_crypto.c
        /// (Mathias Lafeldt, MIT licence).
        /// </summary>
        private static uint MulInverse(uint word)
        {
            if (word == 1) return 1;

            uint a2 = (uint)(-(int)word) % word;
            if (a2 == 0) return 1;

            uint t1 = 1;
            uint a3 = word;
            uint a0 = unchecked((uint)(-(int)(0xFFFFFFFF / word)));

            do
            {
                uint v0 = a3 / a2;
                uint v1 = a3 % a2;
                uint a1 = a2;
                a3 = a1;
                a1 = a0;
                a2 = v1;
                v0 = v0 * a1;
                a0 = t1 - v0;
                t1 = a1;
            } while (a2 != 0);

            return t1;
        }

        private static uint MulDecrypt(uint a, uint b) => a * MulInverse(b | 1);
        private static uint MulEncrypt(uint a, uint b) => a * (b | 1);

        // -----------------------------------------------------------------------
        // Big-integer modular exponentiation  (64-bit, used for RSA-like step)
        // -----------------------------------------------------------------------

        /// <summary>
        /// Computes <c>base^exp mod modulus</c> using fast exponentiation (square-and-multiply).
        /// All arithmetic is in 128-bit (via ulong + carry tracking), keeping only 64-bit results.
        /// </summary>
        private static ulong ModPow64(ulong baseVal, ulong exp, ulong mod)
        {
            if (mod == 1) return 0;
            ulong result = 1;
            baseVal %= mod;
            while (exp > 0)
            {
                if ((exp & 1) == 1)
                    result = MulMod64(result, baseVal, mod);
                exp >>= 1;
                baseVal = MulMod64(baseVal, baseVal, mod);
            }
            return result;
        }

        private static ulong MulMod64(ulong a, ulong b, ulong mod)
        {
            // Use 128-bit multiply via splitting into high/low 32-bit halves
            ulong aLo = a & 0xFFFFFFFF, aHi = a >> 32;
            ulong bLo = b & 0xFFFFFFFF, bHi = b >> 32;

            ulong p0 = aLo * bLo;
            ulong p1 = aLo * bHi;
            ulong p2 = aHi * bLo;
            ulong p3 = aHi * bHi;

            ulong mid  = (p0 >> 32) + (p1 & 0xFFFFFFFF) + (p2 & 0xFFFFFFFF);
            ulong high = p3 + (p1 >> 32) + (p2 >> 32) + (mid >> 32);
            ulong low  = (p0 & 0xFFFFFFFF) | (mid << 32);

            // Compute (high:low) mod mod
            // Since mod < 2^64, and result < mod^2 < 2^128, we do long division
            // using the standard 128-bit mod algorithm.
            return Mod128(high, low, mod);
        }

        private static ulong Mod128(ulong hi, ulong lo, ulong m)
        {
            // Barrett reduction is complex; use bit-by-bit approach for correctness
            ulong r = hi % m;
            for (int i = 63; i >= 0; i--)
            {
                r = (r >= (m - r)) ? r + r - m : r + r; // double with mod
                if (r >= m) r -= m;
                if (((lo >> i) & 1) != 0)
                {
                    r++;
                    if (r >= m) r -= m;
                }
            }
            return r;
        }

