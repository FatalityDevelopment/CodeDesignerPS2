"""Generate CHARACTERS.md: every character skin on the disc, grouped by map package, with the chartypes that spawn it.

Read-only: walks the ISO's RUN/*.ZDB archives, reads each package's CLIB_MDL.ZED model list (MESH_<model> nodes,
type 3) and matches models against chartypes.tsv (the game's chartype registry: name <TAB> model, dumped from
*(0x004500E0) in a running game).

    python characters_readme.py "F:/SOCOM II - U.S. Navy SEALs.iso"
"""
import os
import re
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
BS = chr(92)

# campaign missions have no loading-screen title in their package; regions from their characters
SP_REGION = {"M5": "Albania", "M6": "Brazil", "M7": "Algeria", "M8": "Russia"}


def iso_listing(iso):
    """{path: (size, lba)} for every file on an ISO-9660 image."""
    def sec(n, c=1):
        iso.seek(n * 2048)
        return iso.read(2048 * c)

    out = {}

    def walk(rec, path):
        lba, size = struct.unpack_from("<I", rec, 2)[0], struct.unpack_from("<I", rec, 10)[0]
        data, p = sec(lba, (size + 2047) // 2048), 0
        while p < size:
            ln = data[p]
            if ln == 0:
                p = (p // 2048 + 1) * 2048
                continue
            r = data[p:p + ln]
            name = r[33:33 + r[32]]
            if name not in (b"\0", b"\1"):
                n = name.decode("latin1").split(";")[0]
                if r[25] & 2:
                    walk(r, f"{path}/{n}")
                else:
                    out[f"{path}/{n}"] = (struct.unpack_from("<I", r, 10)[0], struct.unpack_from("<I", r, 2)[0])
            p += ln

    walk(sec(16)[156:190], "")
    return out


def zdb_entries(iso, size, lba):
    iso.seek(lba * 2048)
    d = iso.read(size)
    n, cur, out = struct.unpack_from("<I", d, 0x98)[0], 0xA0, {}
    for _ in range(n):
        hs = struct.unpack_from("<I", d, cur)[0]
        full = d[cur + 4:cur + 0x44].split(b"\0")[0].decode()
        off, sz = struct.unpack_from("<II", d, cur + 0x44)
        out[full] = d[off:off + sz]
        cur += hs
    return out


def zed_models(data):
    """MESH_<model> nodes (type 3) of a ZED container (header 0x64, string table, 16-byte records)."""
    slots, st_size, base = struct.unpack_from("<III", data, 0x04)
    first, models = 0x64 + st_size + 0x10, []
    for i in range(slots - 1):
        name_ptr, _, _, typ = struct.unpack_from("<IIII", data, first + 16 * i)
        so = 0x64 + name_ptr - base
        name = data[so:data.index(b"\0", so)].decode("latin1")
        if typ == 3 and name.startswith("MESH_"):
            models.append(name[5:])
    return models


def main(iso_path):
    chartypes = {}
    for line in open(os.path.join(HERE, "chartypes.tsv"), encoding="utf-8"):
        name, _, model = line.rstrip("\n").partition("\t")
        if model:
            chartypes.setdefault(model, []).append(name)
    iso = open(iso_path, "rb")
    packages = []
    for path, (size, lba) in sorted(iso_listing(iso).items()):
        m = re.match(r"/RUN/(M\w+)\.ZDB$", path)
        if not m:
            continue
        mid, ent = m.group(1), zdb_entries(iso, size, lba)
        clib = [k for k in ent if k.upper().endswith(BS + "CLIB_MDL.ZED")]
        if not clib:
            continue
        kind = clib[0].split(BS)[1].lower()
        extra = []                                            # characters in the package's OTHER model libraries
        for key, blob in ent.items():
            parts = key.split(BS)
            if not key.upper().endswith("_MDL.ZED") or key == clib[0] or len(parts) < 4 or parts[1].lower() != kind:
                continue
            prefix = parts[-1][:-8]                           # MP10_MDL.ZED -> MP10, BM52_MDL.ZED -> BM52
            lib = f"//{kind}/{mid.lower()}" if prefix.upper() == mid else f"//{kind}/{mid.lower()}/{prefix.lower()}"
            for mdl in zed_models(blob):
                if mdl in chartypes and not re.search(r"_[12](_LO)?$", mdl):
                    extra.append((mdl, lib))
        title = None
        for v in ent.values():
            i = v.find(b"description\x00")
            if i >= 0:
                nxt = v[i + 12:i + 60].split(b"\x00")[0]
                if re.fullmatch(rb"[A-Z0-9' .\-]{3,30}", nxt):
                    title = nxt.decode()
                    break
        models = [x for x in zed_models(ent[clib[0]]) if not re.search(r"_[12](_LO)?$", x)]   # drop low-detail copies
        packages.append((kind, mid, title, models, extra))

    out = ["# SOCOM II character skins by package", "",
           "Every character model on the disc, grouped by the map package (`RUN/<MAP>.ZDB`) whose character library",
           "(`clib`) contains it, with the chartypes (`ai` spawn names) that use it, plus characters that live in a",
           "package's other model libraries. Generated by `characters_readme.py`",
           "from the retail ISO and `chartypes.tsv` (the game's chartype registry). Low-detail `_1`/`_2` copies are omitted.",
           "", "## Spawning one", "",
           "A map's own characters are always loaded. To use another package's characters, load its library once per",
           "map load (archive swap + models + VRAM/palette placement), then spawn:", "",
           "```bash", "python Mods/SOCOM2/bots/socom_bots.py loadlib //mp/mp53/clib",
           "python Mods/SOCOM2/bots/socom_bots.py ai mp_algerian_h1 here team=0x40020000", "```", "",
           "- Campaign packages work the same way: `loadlib //sp/m51/clib`.",
           "- Only one `loadlib` per map load for now (a second archive swap in the same session has frozen the game).",
           "- `team=`: `0x40020000` = escortable VIP (SEAL side in MP), `0x80020000` = escortable on the terrorist side.",
           "- Chartypes named `UiCharType*` / `netchar*` / `mpNN_*` are the player skins; any chartype listed for a model",
           "  spawns that model.", ""]
    for kind, label in (("mp", "Multiplayer maps"), ("sp", "Campaign missions")):
        out += [f"## {label}", ""]
        for k, mid, title, models, extra in packages:
            if k != kind:
                continue
            name = title.title() if title else f"{SP_REGION.get(mid[:2], '')} mission {mid}".strip()
            out += [f"### {mid} - {name}", "", f"Library: `//{kind}/{mid.lower()}/clib`", "",
                    "| Model | Spawn as (chartypes) |", "|---|---|"]
            for mdl in models:
                names = chartypes.get(mdl, [])
                shown = ", ".join(f"`{n}`" for n in names[:6]) + (f" (+{len(names) - 6})" if len(names) > 6 else "")
                out.append(f"| `{mdl}` | {shown or '_no registered chartype_'} |")
            if extra:
                out += ["", "Also in this package, outside `clib` (loadlib placement for these library types is not"
                        " implemented yet - only character libraries, category 0x10):", "",
                        "| Model | Library | Spawn as |", "|---|---|---|"]
                for mdl, lib in extra:
                    out.append(f"| `{mdl}` | `{lib}` | " + ", ".join(f"`{n}`" for n in chartypes[mdl][:6]) + " |")
            out.append("")
    dest = os.path.join(HERE, "..", "CHARACTERS.md")
    open(dest, "w", encoding="utf-8").write("\n".join(out))
    print(f"wrote {os.path.normpath(dest)}: {len(packages)} packages")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "F:/SOCOM II - U.S. Navy SEALs.iso")
