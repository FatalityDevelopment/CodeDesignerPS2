using CodeDesigner.Ps2.Compression;
using Microsoft.VisualStudio.TestTools.UnitTesting;

namespace CodeDesigner.Ps2.TestProject
{
    [TestClass]
    public sealed class TestApacheRuntimeCrypto
    {
        private static readonly byte[] VerifiedEncryptedSecurityBlock =
        {
            0x80, 0x04, 0x60, 0xAA, 0xF6, 0x04, 0x00, 0x94, 0xD8, 0x64, 0x00, 0x80, 0xF4, 0x24, 0x00, 0xC4,
            0x78, 0x00, 0x3F, 0x01, 0x50, 0x00, 0xA7, 0x05, 0x08, 0x00, 0xB2, 0x05, 0xC8, 0x22, 0x20, 0x0B,
            0x56, 0x00, 0x05, 0x3C, 0xF4, 0x04, 0x00, 0x98, 0xA8, 0x76, 0xA5, 0x24, 0xDA, 0x55, 0x06, 0x0C,
            0x80, 0x04, 0x00, 0xC2, 0x88, 0x22, 0x60, 0x0A, 0x82, 0x04, 0xFB, 0x44, 0xF4, 0x04, 0x00, 0x50,
            0x00, 0x00, 0xA5, 0x05, 0x08, 0x00, 0xB3, 0x05, 0x50, 0x00, 0x22, 0xA4, 0x4C, 0x00, 0x24, 0xA4,
        };

        private static readonly byte[] VerifiedPlaintextSecurityBlock =
        {
            0x53, 0x00, 0x05, 0x24, 0xA0, 0x00, 0xB4, 0x27, 0x00, 0x03, 0xC4, 0x26, 0x20, 0x01, 0xA6, 0x27,
            0x09, 0xF8, 0xC0, 0x03, 0x2D, 0x38, 0x80, 0x02, 0x2D, 0x90, 0x40, 0x00, 0x59, 0x01, 0x40, 0x16,
            0x56, 0x00, 0x05, 0x3C, 0xC0, 0x00, 0xA4, 0x27, 0xA8, 0x76, 0xA5, 0x24, 0xDA, 0x55, 0x06, 0x0C,
            0x10, 0x00, 0x06, 0x24, 0x53, 0x01, 0x40, 0x14, 0x27, 0xD8, 0x12, 0x24, 0x80, 0x00, 0xA2, 0x27,
            0x2D, 0x28, 0x00, 0x00, 0x2D, 0x98, 0x40, 0x00, 0x21, 0x10, 0x85, 0x02, 0x21, 0x20, 0x65, 0x02,
        };

        private const uint VerifiedRawDispatchWord = 0xBAFA4B78u;
        private static readonly int[] VerifiedExcludedWordIndices = { 8, 10, 11 };

        [TestMethod]
        public void TestEncodeDispatchWordMatchesVerifiedExample()
        {
            uint encoded = ZdbDispatchWordCodec.EncodeFromRuntimeWord(VerifiedRawDispatchWord);
            int[] indices = ZdbDispatchWordCodec.DecodeTransformIndices(encoded);

            Assert.AreEqual(0x32724370u, encoded);
            CollectionAssert.AreEqual(new[] { 0, 7, 3 }, indices);
        }

        [TestMethod]
        public void TestDecryptSecurityBlockMatchesVerifiedPlaintext()
        {
            byte[] decrypted = ApacheSecurityBlockCrypto.DecryptBlock(
                VerifiedEncryptedSecurityBlock,
                VerifiedRawDispatchWord,
                VerifiedExcludedWordIndices);

            CollectionAssert.AreEqual(VerifiedPlaintextSecurityBlock, decrypted);
        }

        [TestMethod]
        public void TestEncryptSecurityBlockMatchesVerifiedCiphertext()
        {
            byte[] encrypted = ApacheSecurityBlockCrypto.EncryptBlock(
                VerifiedPlaintextSecurityBlock,
                VerifiedRawDispatchWord,
                VerifiedExcludedWordIndices);

            CollectionAssert.AreEqual(VerifiedEncryptedSecurityBlock, encrypted);
        }
    }
}
